"""Import the DNA ladder definitions bundled with ApE (A plasmid Editor, M. Wayne Davis,
https://jorgensen.biology.utah.edu/wayned/ape/) into autogel/ladders_ape.json.

ApE for Windows is a single Tcl "starpack" executable; its support files are stored inside it
as zlib streams. This script only READS the file as bytes and decompresses those streams - it
never executes anything.

ApE ladder format: one ladder per line, ``name<TAB>sizes`` with sizes in decreasing order;
a size repeated n times means a band n times as bright (e.g. ``3001 3001 3001``).

Usage:  python -I tools/import_ape_ladders.py path/to/ApE.exe
"""
from __future__ import annotations

import json
import os
import re
import sys
import zlib
from collections import OrderedDict

LINE = re.compile(r"^([^\t#][^\t]*)\t\s*([\d ]+)\s*$")
VENDORS = [  # catalog-number patterns used in ApE's ladder names
    (re.compile(r"\((?:N|P)\d{4}\)$"), "NEB"),
    (re.compile(r"\(G\d{3,4}\)$"), "Promega"),
    (re.compile(r"\((?:\d{5}|10488-\d{3})\)$"), "Invitrogen"),
    (re.compile(r"\((?:D|P|S)\d{4}\)$"), "Sigma"),
]


def streams(blob: bytes):
    for m in re.finditer(rb"\x78[\x01\x5e\x9c\xda]", blob):
        try:
            t = zlib.decompressobj().decompress(blob[m.start(): m.start() + 200000])
        except zlib.error:
            continue
        if t:
            yield t


def parse(blob: bytes) -> OrderedDict:
    out: OrderedDict = OrderedDict()
    for t in streams(blob):
        try:
            text = t.decode("utf-8")
        except UnicodeDecodeError:
            continue
        for line in text.splitlines():
            m = LINE.match(line)
            if m and len(m.group(2).split()) >= 3:
                out.setdefault(m.group(1).strip(), [int(x) for x in m.group(2).split()])
    return out


def to_entry(name: str, raw: list[int]) -> dict:
    # unique sizes with brightness weight = number of repeats
    sizes, weight = [], []
    for s in raw:
        if sizes and s == sizes[-1]:
            weight[-1] += 1
        else:
            sizes.append(s)
            weight.append(1)
    # merge co-migrating doublets (<= 4 % apart, e.g. 517/500) into one band
    m_sizes, m_weight, merged = [sizes[0]], [weight[0]], []
    for s, w in zip(sizes[1:], weight[1:]):
        if (m_sizes[-1] - s) / m_sizes[-1] <= 0.04:
            merged.append(f"{m_sizes[-1]}/{s}")
            m_sizes[-1] = s          # label with the smaller size (vendor charts: "0.5 kb")
            m_weight[-1] += w
        else:
            m_sizes.append(s)
            m_weight.append(w)
    vendor = next((v for rx, v in VENDORS if rx.search(name)), "")
    cat = re.search(r"\(([^()]+)\)$", name)
    unit = "bp"
    note = "Imported from ApE; sizes only (no masses). relative_intensity = repeat count in ApE."
    if merged:
        note += f" Merged co-migrating doublets: {', '.join(merged)}."
    if max(m_sizes) > 50000:
        note += " Pulsed-field marker."
    return {"name": f"{vendor} {name}".strip() if vendor and not name.startswith(vendor) else name,
            "vendor": vendor, "catalog": cat.group(1) if cat else "", "unit": unit,
            "sizes": m_sizes, "relative_intensity": m_weight, "masses": None,
            "note": note, "source": "ApE (A plasmid Editor) DNA_ladders, ApE_win_current.zip",
            "source_db": "ApE", "verified": False}


def main(exe: str):
    with open(exe, "rb") as f:
        blob = f.read()
    ladders = parse(blob)
    entries = [to_entry(n, s) for n, s in ladders.items()]
    entries = [e for e in entries if e["sizes"] == sorted(e["sizes"], reverse=True)]
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "autogel", "ladders_ape.json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump({"format": 2, "description": "DNA ladders imported from ApE (sizes + relative "
                   "brightness only, unverified). Generated by tools/import_ape_ladders.py.",
                   "ladders": entries}, f, indent=1, ensure_ascii=False)
    print(f"{len(entries)} ladders -> {os.path.normpath(dst)}")


if __name__ == "__main__":
    main(sys.argv[1])
